#!/usr/bin/env bash
# Regenerates src/db/schema/auth.ts from the Better Auth config, then applies the
# project convention that every timestamp is timestamptz (database-design.md §1).
set -euo pipefail
cd "$(dirname "$0")/.."
out=src/db/schema/auth.ts
pnpm exec auth generate --config better-auth.config.ts --output "$out" --yes
sed -i.bak -E 's/timestamp\("([a-z_]+)"\)/timestamp("\1", { withTimezone: true })/g' "$out"
rm -f "$out.bak"
{
  echo "// Generated by scripts/generate-auth-schema.sh from Better Auth. Do not edit by hand."
  cat "$out"
} > "$out.tmp" && mv "$out.tmp" "$out"
pnpm exec prettier --write "$out" > /dev/null
